"""Local staging/demo environment bootstrap.

Ensures the `.env` file contains everything the compose stack and the
rehearsal runner need, without ever overwriting a value a human already set.

Design rules:

* Secrets are **generated locally** with `secrets.token_urlsafe`, written to
  `.env` (gitignored), and never printed. `--show` refuses to print them.
* Existing non-empty values always win. This target is safe to re-run.
* The Groq key cannot be invented. If `ITSM_GROQ_API_KEY` is absent it is
  copied from a `GROQ_API_KEY` already present in the environment or in
  `.env`; if there is none, the script says so and exits non-zero, because a
  demo without a real model must not start silently.
* Ports are chosen away from the defaults so the demo stack does not collide
  with a locally running PostgreSQL (the developer machine has one on 5432).

Usage:
    python tools/demo_env.py ensure [--env-file .env]
    python tools/demo_env.py status [--env-file .env]   # names only, no values
"""

from __future__ import annotations

import argparse
import os
import secrets
import sys
from pathlib import Path

#: Ports the demo stack publishes on the host. Chosen off the defaults so a
#: developer's own PostgreSQL/NATS are not disturbed.
DEMO_PORTS: dict[str, str] = {
    "POSTGRES_HOST_PORT": "5532",
    "NATS_HOST_PORT": "4223",
    "NATS_MONITOR_HOST_PORT": "8223",
    "MOCKOON_HOST_PORT": "3002",
    "API_HOST_PORT": "8001",
    "PROMETHEUS_HOST_PORT": "9091",
    "IDENTITY_HOST_PORT": "8444",
}

#: Non-secret wiring shared by the compose stack and the host-side runner.
STATIC_VALUES: dict[str, str] = {
    "POSTGRES_DB": "itsm",
    "POSTGRES_USER": "itsm",
    "ITSM_ENV": "staging",
    "ITSM_AUTH_MODE": "oidc",
    "ITSM_OIDC_ISSUER": "https://identity:8443",
    "ITSM_OIDC_AUDIENCE": "itsm-audience",
    "ITSM_OIDC_JWKS_URL": "https://identity:8443/jwks",
    "ITSM_OIDC_ALGORITHMS": "RS256",
    # Host-side surfaces (published loopback ports).
    "ITSM_API_BASE_URL": "http://127.0.0.1:8001",
    "ITSM_IDENTITY_BASE_URL": "https://127.0.0.1:8444",
    "ITSM_IDENTITY_CA_FILE": "./demo-state/identity/simulator-ca.pem",
    "ITSM_NATS_URL": "nats://127.0.0.1:4223",
    "ITSM_REVIEWER_SUBJECT_A": "reviewer-a",
    "ITSM_REVIEWER_SUBJECT_B": "reviewer-b",
    "ITSM_INVESTIGATION_ENABLED": "true",
    "ITSM_INVESTIGATION_LLM_BUDGET_CALLS": "3",
    "ITSM_INVESTIGATION_MAX_MODEL_CALLS": "2",
    "ITSM_INVESTIGATION_MAX_TOOL_CALLS": "5",
    "ITSM_PROMETHEUS_URL": "http://127.0.0.1:9091",
}

#: Generated when absent. Never printed.
SECRET_KEYS: tuple[str, ...] = (
    "POSTGRES_PASSWORD",
    "ITSM_RUNTIME_DB_PASSWORD",
    "ITSM_WEBHOOK_SECRET",
)


def read_env(path: Path) -> dict[str, str]:
    """Parse a dotenv file into a dict (last assignment wins)."""
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()
    return values


def _append(path: Path, additions: list[tuple[str, str]]) -> None:
    if not additions:
        return
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    with path.open("a", encoding="utf-8") as handle:
        if existing and not existing.endswith("\n"):
            handle.write("\n")
        if (
            "\n# --- local staging/demo stack (generated by tools/demo_env.py) ---\n"
            not in existing
        ):
            handle.write("\n# --- local staging/demo stack (generated by tools/demo_env.py) ---\n")
        for key, value in additions:
            handle.write(f"{key}={value}\n")


def ensure(path: Path, environ: dict[str, str] | None = None) -> tuple[list[str], list[str]]:
    """Ensure required keys exist. Returns (added_keys, problems)."""
    env = dict(environ if environ is not None else os.environ)
    current = read_env(path)
    additions: list[tuple[str, str]] = []
    problems: list[str] = []

    def have(key: str) -> bool:
        return bool(current.get(key) or env.get(key))

    for key, value in STATIC_VALUES.items():
        if not have(key):
            additions.append((key, value))

    for key, value in DEMO_PORTS.items():
        if not have(key):
            additions.append((key, value))

    for key in SECRET_KEYS:
        if not have(key):
            additions.append((key, secrets.token_urlsafe(32)))

    if not have("ITSM_GROQ_API_KEY"):
        inherited = env.get("GROQ_API_KEY") or current.get("GROQ_API_KEY") or ""
        if inherited:
            additions.append(("ITSM_GROQ_API_KEY", inherited))
        else:
            problems.append(
                "ITSM_GROQ_API_KEY is not set and no GROQ_API_KEY was found to "
                "inherit. The live investigation stage is required for the demo, "
                "so it is not silently disabled — export ITSM_GROQ_API_KEY first."
            )

    if not have("ITSM_POSTGRES_DSN"):
        password = (
            dict(additions).get("POSTGRES_PASSWORD") or current.get("POSTGRES_PASSWORD") or ""
        )
        if password:
            additions.append(
                (
                    "ITSM_POSTGRES_DSN",
                    "postgresql://itsm:" + password + "@127.0.0.1:5532/itsm",
                )
            )

    _append(path, additions)
    return [key for key, _ in additions], problems


def status(path: Path) -> int:
    """Print which keys are present. Never prints a value."""
    values = read_env(path)
    required = list(STATIC_VALUES) + list(DEMO_PORTS) + list(SECRET_KEYS)
    missing = [key for key in required if not values.get(key)]
    print(f"env file: {path} ({'present' if path.exists() else 'MISSING'})")
    print(f"keys present: {len(required) - len(missing)}/{len(required)}")
    if missing:
        print("missing: " + ", ".join(missing))
        return 1
    print("groq key: " + ("set" if values.get("ITSM_GROQ_API_KEY") else "MISSING"))
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("ensure", "status"))
    parser.add_argument("--env-file", default=".env")
    args = parser.parse_args(argv)
    path = Path(args.env_file)

    if args.command == "status":
        return status(path)

    added, problems = ensure(path)
    if added:
        # Names only: a value must never reach a log.
        print("added keys: " + ", ".join(added))
    else:
        print("env already complete — nothing changed")
    for problem in problems:
        print(f"ERROR: {problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":  # pragma: no cover - process boundary
    raise SystemExit(main())
